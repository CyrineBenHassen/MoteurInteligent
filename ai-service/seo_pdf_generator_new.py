def _build_category_chart(elements, test_cases):
    elements.append(_section_header('Category Breakdown Chart', '#16a34a'))
    elements.append(Spacer(1, 8))

    cats = {}
    for tc in test_cases:
        cat = tc.get('category', 'technical')
        cats.setdefault(cat, {'pass': 0, 'fail': 0})
        if tc.get('status') == 'pass':
            cats[cat]['pass'] += 1
        else:
            cats[cat]['fail'] += 1

    categories = list(cats.keys())
    passed = [cats[c]['pass'] for c in categories]
    failed = [cats[c]['fail'] for c in categories]

    fig, ax = plt.subplots(figsize=(6.6, 3.0), dpi=150)
    x = range(len(categories))
    ax.bar(x, passed, color='#10b981', label='Passed')
    ax.bar(x, failed, bottom=passed, color='#ef4444', label='Failed')
    ax.set_xticks(list(x))
    ax.set_xticklabels([c.upper() for c in categories], rotation=40, ha='right', fontsize=7)
    ax.set_ylabel('Checks', fontsize=8)
    ax.tick_params(axis='y', labelsize=7)
    ax.legend(fontsize=7, loc='upper right', frameon=False)
    ax.spines['top'].set_visible(False)
    ax.spines['right'].set_visible(False)
    fig.tight_layout()

    img_buf = BytesIO()
    fig.savefig(img_buf, format='PNG', transparent=True)
    plt.close(fig)
    img_buf.seek(0)

    elements.append(Image(img_buf, width=160*mm, height=72*mm))
    elements.append(Spacer(1, 16))


