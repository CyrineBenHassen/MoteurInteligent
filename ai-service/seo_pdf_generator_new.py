def _decode_screenshot(raw):
    """Accepts either raw PNG bytes (internal calls) or a base64 string
    (as received over the /generate-pdf JSON endpoint) and returns bytes or None."""
    if not raw:
        return None
    if isinstance(raw, (bytes, bytearray)):
        return bytes(raw)
    if isinstance(raw, str):
        try:
            return base64.b64decode(raw)
        except Exception as e:
            print(f"[SEO PDF] Failed to decode screenshot base64: {e}")
            return None
    return None


def on_page_seo(canvas, doc):
    W, H = A4
    canvas.saveState()
    canvas.setFillColor(NAVY)
    canvas.rect(0, H - 52*mm, W, 52*mm, fill=1, stroke=0)
    canvas.setFillColor(SEO_GREEN)
    canvas.rect(0, H - 54*mm, W, 2*mm, fill=1, stroke=0)
    canvas.setFillColor(SEO_GREEN)
    canvas.rect(0, 0, 3, H - 54*mm, fill=1, stroke=0)
    canvas.setFillColor(LIGHT_BG)
    canvas.rect(0, 0, W, 14*mm, fill=1, stroke=0)
    canvas.setFillColor(BORDER)
    canvas.rect(0, 14*mm, W, 0.5, fill=1, stroke=0)
    canvas.setFont('Helvetica', 7.5)
    canvas.setFillColor(MUTED)
    canvas.drawString(20*mm, 5*mm, 'Generated by NexTest — SEO Test Report')
    canvas.drawRightString(W - 20*mm, 5*mm,
        f'Page {doc.page}  •  {datetime.now().strftime("%Y-%m-%d")}')
    canvas.restoreState()


def _section_header(text, color=None):
    accent = HexColor(color) if isinstance(color, str) else (color or SEO_GREEN)
    tbl = Table([[_p(f'<b>{text}</b>',
        _ps('SH', fontSize=11, fontName='Helvetica-Bold',
            textColor=DARK_TEXT, leading=14))
    ]], colWidths=[168*mm])
    tbl.setStyle(TableStyle([
        ('LINEBELOW',     (0,0), (-1,-1), 1.5, accent),
        ('BOTTOMPADDING', (0,0), (-1,-1), 6),
        ('TOPPADDING',    (0,0), (-1,-1), 0),
    ]))
    return tbl


