# ── Section 2 : Test Summary ───────────────────────────────────────────────────

def build_api_stats_section(elements, execution_results: list):
    total      = len(execution_results)
    pass_count = sum(1 for r in execution_results if r.get('status') == 'pass')
    fail_count = sum(1 for r in execution_results if r.get('status') == 'fail')
    skip_count = sum(1 for r in execution_results if r.get('status') == 'skip')
    rate       = round(pass_count / total * 100) if total else 0
    rate_hex   = '#10b981' if rate >= 80 else '#f59e0b' if rate >= 50 else '#ef4444'
    rate_bg    = GREEN_BG  if rate >= 80 else ORANGE_BG  if rate >= 50 else RED_BG

    avg_duration = _avg_duration(execution_results)

    stats_data = [[
        stat_card(pass_count, 'PASSED',      '#10b981', GREEN_BG),
        stat_card(fail_count, 'FAILED',      '#ef4444', RED_BG),
        stat_card(skip_count, 'SKIPPED',     '#f59e0b', ORANGE_BG),
        stat_card(f'{rate}%', 'PASS RATE',   rate_hex,  rate_bg),
        stat_card(total,      'TOTAL',       '#3b82f6', BLUE_BG),
        stat_card(avg_duration, 'AVG TIME',  '#8b5cf6', PURPLE_BG),
    ]]
    outer = Table(stats_data, colWidths=[28*mm]*6)
    outer.setStyle(TableStyle([
        ('ALIGN',  (0,0), (-1,-1), 'CENTER'),
        ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
        ('PADDING',(0,0), (-1,-1), 2),
    ]))
    elements.append(outer)
    elements.append(Spacer(1, 14))

    # Pass rate bar
    bar_data = [[Paragraph(
        f'<font color="{rate_hex}" size="9"><b>Overall Pass Rate: {rate}%</b></font>  '
        f'<font color="#94a3b8" size="8">({pass_count} passed / {fail_count} failed / {skip_count} skipped / {total} total)</font>',
        ParagraphStyle('RB', fontSize=9, fontName='Helvetica', leading=12))]]
    bar_outer = Table(bar_data, colWidths=[168*mm])
    bar_outer.setStyle(TableStyle([
        ('BACKGROUND',    (0,0), (-1,-1), rate_bg),
        ('BOX',           (0,0), (-1,-1), 1, HexColor(rate_hex)),
        ('LEFTPADDING',   (0,0), (-1,-1), 12),
        ('TOPPADDING',    (0,0), (-1,-1), 8),
        ('BOTTOMPADDING', (0,0), (-1,-1), 8),
    ]))
    elements.append(bar_outer)
    elements.append(Spacer(1, 16))


