# ── Private Helpers ────────────────────────────────────────────────────────────

def _lbl(text: str):
    return Paragraph(f'<font color="#64748b">{text}</font>',
                     ParagraphStyle('IL', fontSize=8, fontName='Helvetica-Bold', leading=12))

def _lbl_w(text: str):
    return Paragraph(f'<font color="#64748b"><b>{text}</b></font>',
                     ParagraphStyle('ILW', fontSize=8, fontName='Helvetica-Bold', leading=11))

def _val(text: str):
    return Paragraph(f'<font color="#1e293b">{text}</font>',
                     ParagraphStyle('IV', fontSize=8.5, fontName='Helvetica', leading=12))

def _status_code_badge(code) -> str:
    c = int(code) if str(code).isdigit() else 0
    if c == 200 or c == 201:   color = '#10b981'
    elif c == 401 or c == 403: color = '#f59e0b'
    elif c == 404:              color = '#3b82f6'
    elif c == 422:              color = '#8b5cf6'
    elif c >= 500:              color = '#ef4444'
    else:                       color = '#64748b'
    return f'<font color="{color}"><b>{code}</b></font>'

def _status_result_colors(status: str) -> tuple:
    """Returns (text_color_hex, bg_color_hex)"""
    if status == 'pass':   return '#10b981', '#f0fdf4'
    elif status == 'fail': return '#ef4444', '#fef2f2'
    else:                  return '#f59e0b', '#fffbeb'

def _avg_duration(execution_results: list) -> str:
    ms = _avg_duration_ms(execution_results)
    if ms == 0: return '—'
    return f'{ms}ms' if ms < 1000 else f'{ms/1000:.1f}s'

def _avg_duration_ms(execution_results: list) -> int:
    vals = []
    for r in execution_results:
        ms = _parse_duration_ms(r.get('duration', '—'))
        if ms > 0:
            vals.append(ms)
    return round(sum(vals) / len(vals)) if vals else 0

def _parse_duration_ms(duration: str) -> int:
    if not duration or duration == '—':
        return 0
    try:
        d = str(duration).strip().lower()
        if d.endswith('ms'):  return int(float(d[:-2]))
        elif d.endswith('s'): return int(float(d[:-1]) * 1000)
        return int(float(d))
    except Exception:
        return 0