# ── Page Chrome ────────────────────────────────────────────────────────────────

def on_page_api(canvas, doc):
    W, H = A4
    canvas.saveState()
    # Top bar
    canvas.setFillColor(NAVY)
    canvas.rect(0, H - 52*mm, W, 52*mm, fill=1, stroke=0)
    canvas.setFillColor(POSTMAN_COLOR)
    canvas.rect(0, H - 54*mm, W, 2*mm, fill=1, stroke=0)
    # Left accent
    canvas.setFillColor(POSTMAN_COLOR)
    canvas.rect(0, 0, 3, H - 54*mm, fill=1, stroke=0)
    # Footer
    canvas.setFillColor(LIGHT_BG)
    canvas.rect(0, 0, W, 14*mm, fill=1, stroke=0)
    canvas.setFillColor(BORDER)
    canvas.rect(0, 14*mm, W, 0.5, fill=1, stroke=0)
    canvas.setFont('Helvetica', 7.5)
    canvas.setFillColor(MUTED)
    canvas.drawString(20*mm, 5*mm, 'Generated by NexTest — AI-Powered API Test Automation')
    canvas.drawRightString(W - 20*mm, 5*mm, f'Page {doc.page}  •  {datetime.now().strftime("%Y-%m-%d")}')
    canvas.restoreState()


# ── Shared Helpers ─────────────────────────────────────────────────────────────

def section_header(emoji, text, color=None):
    accent = color or POSTMAN_COLOR
    data = [[Paragraph(
        f'{emoji}  {text}',
        ParagraphStyle('SH', fontSize=11, fontName='Helvetica-Bold',
                       textColor=DARK_TEXT, leading=14))]]
    tbl = Table(data, colWidths=[168*mm])
    tbl.setStyle(TableStyle([
        ('LINEBELOW',     (0,0), (-1,-1), 1.5, accent),
        ('BOTTOMPADDING', (0,0), (-1,-1), 6),
        ('TOPPADDING',    (0,0), (-1,-1), 0),
    ]))
    return tbl


def stat_card(value, label, val_color, bg_color):
    inner = [[Paragraph(
        f'<font color="{val_color}"><b>{value}</b></font><br/>'
        f'<font color="#94a3b8" size="7"><b>{label}</b></font>',
        ParagraphStyle('SC', fontSize=18, fontName='Helvetica-Bold',
                       alignment=TA_CENTER, leading=26))]]
    t = Table(inner, colWidths=[30*mm])
    t.setStyle(TableStyle([
        ('BACKGROUND',    (0,0), (-1,-1), bg_color),
        ('BOX',           (0,0), (-1,-1), 1, BORDER_DARK),
        ('TOPPADDING',    (0,0), (-1,-1), 12),
        ('BOTTOMPADDING', (0,0), (-1,-1), 12),
        ('ALIGN',         (0,0), (-1,-1), 'CENTER'),
    ]))
    return t


def method_badge(method: str) -> str:
    color, _ = METHOD_COLORS.get(method.upper(), ('#64748b', '#f8fafc'))
    return f'<font color="{color}"><b>{method.upper()}</b></font>'


def _fw_display(framework: str) -> tuple:
    """Returns (display_name, color_hex_str, bg_color, short_label)"""
    fw = framework.lower() if framework else ''
    if 'postman' in fw or 'newman' in fw:
        return 'Postman / Newman CLI', '#FF6C37', POSTMAN_BG, 'Po'
    elif 'pytest' in fw:
        return 'Pytest + requests', '#3776AB', PYTEST_BG, 'Py'
    else:
        return framework, '#FF6C37', POSTMAN_BG, (fw[:2].upper() if fw else 'AP')


