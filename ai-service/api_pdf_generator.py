    elements.append(meta_tbl)
    elements.append(Spacer(1, 14))

    # Group test cases by category/domain
    grouped = {}
    for tc in test_cases:
        cat = tc.get('category', 'api')
        grouped.setdefault(cat, []).append(tc)

